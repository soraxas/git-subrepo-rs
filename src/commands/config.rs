use crate::commands::{Context, normalize_subdir};
use crate::git_utils::{run_git, try_run_git};
use anyhow::Result;

pub const VALID_KEYS: &[&str] = &[
    "branch", "cmdver", "commit", "exclude", "method", "parent", "remote", "upstream", "version",
];

pub fn run(subdir: String, key: String, value: Option<String>, force: bool) -> Result<()> {
    let ctx = Context::new()?;

    let subdir = normalize_subdir(&subdir);
    let gitrepo_path = ctx.repo_root.join(&subdir).join(".gitrepo");
    let gitrepo_path_str = gitrepo_path.to_string_lossy().into_owned();

    if !VALID_KEYS.contains(&key.as_str()) {
        anyhow::bail!("Option {key} not recognized");
    }
    if !gitrepo_path.is_file() {
        anyhow::bail!("Not a subrepo: {subdir} (no .gitrepo file)");
    }

    let config_key = format!("subrepo.{key}");

    if value.is_none() {
        // Read mode
        let read_mode = if key == "exclude" {
            "--get-all"
        } else {
            "--get"
        };
        let (ok, out) = try_run_git(
            &[
                "config",
                "--file",
                &gitrepo_path_str,
                read_mode,
                &config_key,
            ],
            &ctx.repo_root,
        );
        if ok {
            println!("Subrepo '{subdir}' option '{key}' has value '{out}'.");
        } else if !gitrepo_path.exists() {
            anyhow::bail!("'{subdir}' has no .gitrepo file (not a subrepo?).");
        } else {
            anyhow::bail!("Subrepo '{subdir}' option '{key}' is not set.");
        }
        return Ok(());
    }

    let val = value.unwrap();

    // Write mode - needs force for most keys
    if !force && key != "method" && key != "exclude" {
        anyhow::bail!("This option is autogenerated, use '--force' to override.");
    }

    if key == "method" && val != "merge" && val != "rebase" {
        anyhow::bail!("Not a valid method. Valid options are 'merge' or 'rebase'.");
    }
    if key == "exclude" {
        crate::exclusions::validate(&val)?;
    }

    let mut args = vec!["config", "--file", &gitrepo_path_str];
    if key == "exclude" {
        args.push("--replace-all");
    }
    args.extend([config_key.as_str(), val.as_str()]);
    run_git(&args, &ctx.repo_root)?;

    println!("Subrepo '{subdir}' option '{key}' set to '{val}'.");

    Ok(())
}
